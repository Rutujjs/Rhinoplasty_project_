"""
Generation manifest – the single source of truth for a batch request.

The manifest is written to disk (as JSON) before any remote submission
and is included in the Kaggle kernel's input dataset so the notebook
knows exactly what to generate.  It is also stored in the database job
record for audit purposes.

Design notes
------------
- All fields are validated by Pydantic before serialisation.
- Secrets (API keys, DB URLs, JWT tokens) are NEVER included.
- The manifest is versioned (schema_version) so future format changes
  can be handled gracefully.
- Seeds are generated by the orchestrator, not the notebook, so results
  are reproducible when a job is retried with the same seed list.
- The ``prompts`` field carries one textual prompt per requested image.
  The notebook reads ``GENERATION_MANIFEST.get("prompts")`` and, when
  the list is present, passes each prompt directly to FLUX.2 Klein.
  ``build_manifest`` always populates this field, so the notebook will
  never silently use its hardcoded fallback prompt for a backend job.
"""

from __future__ import annotations

import json
import secrets
import uuid
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from pydantic import BaseModel, Field, field_validator, model_validator
from generation.viewpoints import VIEWPOINT_KEYS


# Bump this whenever the schema changes in a backward-incompatible way.
MANIFEST_SCHEMA_VERSION = "1.0"


class ManifestProviderConfig(BaseModel):
    """
    Provider-specific configuration that is safe to disclose to the notebook.

    Do NOT add credential fields here.
    """

    provider: str = Field(
        description="Provider name, e.g. MOCK or KAGGLE_BATCH"
    )
    # The notebook loads FLUX.2-klein-4B directly from HuggingFace via
    # Flux2KleinPipeline.from_pretrained("black-forest-labs/FLUX.2-klein-4B").
    # model_dataset_path and base_model_path are kept for future LoRA
    # adapters but are not required for the current pretrained pipeline.
    model_dataset_path: str = Field(
        default="",
        description=(
            "Relative path inside the Kaggle kernel where a LoRA adapter "
            "can be found.  Leave empty when using the pretrained model directly."
        ),
    )
    base_model_path: str = Field(
        default="",
        description=(
            "Base model HuggingFace slug or path, required only when "
            "model_dataset_path points to a LoRA adapter weight file."
        ),
    )
    prompt_template_version: str = Field(
        default="1.0",
        description="Version tag of the prompt template used by the notebook",
    )
    output_format: str = Field(
        default="png",
        description="Image format the notebook should save (png/jpg/webp)",
    )
    num_inference_steps: int = Field(
        default=12,
        description="Denoising steps for the FLUX pipeline",
    )
    guidance_scale: float = Field(
        default=1.0,
        description="Classifier-free guidance scale",
    )


class GenerationManifest(BaseModel):
    """
    Complete specification of a single generation batch.

    This object is serialised to JSON and passed to the generation provider.
    """

    # ------------------------------------------------------------------ #
    # Schema version                                                       #
    # ------------------------------------------------------------------ #
    schema_version: str = Field(default=MANIFEST_SCHEMA_VERSION)

    # ------------------------------------------------------------------ #
    # Identifiers                                                          #
    # ------------------------------------------------------------------ #
    dataset_id: int
    job_id: int
    batch_id: str = Field(
        default_factory=lambda: str(uuid.uuid4()),
        description="Unique identifier for this specific batch within the job",
    )
    patient_id: str = Field(
        default="P01",
        description="Synthetic patient identifier (e.g. P01, patient_001)",
    )
    custom_prompt: str | None = Field(
        default=None,
        description="Customized frontal prompt provided by the user",
    )
    viewpoints: list[str] = Field(
        default_factory=lambda: list(VIEWPOINT_KEYS),
        description="List of viewpoints to generate (frontal + 8 viewpoints)",
    )
    viewpoint_prompts: dict[str, str] | None = Field(
        default=None,
        description="Custom per-viewpoint prompt overrides",
    )

    # ------------------------------------------------------------------ #
    # Generation parameters                                                #
    # ------------------------------------------------------------------ #
    requested_count: int = Field(ge=1, description="Number of images to generate")
    image_width: int = Field(ge=64, le=2048)
    image_height: int = Field(ge=64, le=2048)

    # Demographics / attributes – uses the existing project's terminology.
    population_group: str = Field(min_length=1, max_length=100)
    region: str = Field(min_length=1, max_length=100)
    age_min: int = Field(ge=0, le=120)
    age_max: int = Field(ge=0, le=120)
    sex_or_attribute: str = Field(min_length=1, max_length=50)
    skin_tone: str = Field(min_length=1, max_length=50)
    pose: str = Field(min_length=1, max_length=50)
    expression: str = Field(min_length=1, max_length=50)
    lighting: str = Field(default="neutral", max_length=50)

    # Optional medical context.
    medical_condition: str | None = Field(default=None, max_length=100)
    medical_severity: str | None = Field(default=None, max_length=50)

    # ------------------------------------------------------------------ #
    # Per-image prompts                                                    #
    # One textual prompt per requested image.                              #
    # When present, the notebook MUST use these prompts instead of any    #
    # hardcoded fallback.  When absent (None), legacy notebook behaviour   #
    # is preserved — this allows old manifest files to load cleanly.      #
    # build_manifest() always populates this field for new requests.       #
    # ------------------------------------------------------------------ #
    prompts: list[str] | None = Field(
        default=None,
        description=(
            "One prompt string per requested image. "
            "Must have length == requested_count when not None. "
            "build_manifest() always populates this field."
        ),
    )

    # ------------------------------------------------------------------ #
    # Per-image seeds                                                      #
    # Providing seeds here ensures the notebook is fully reproducible.     #
    # The list length must match requested_count.                          #
    # ------------------------------------------------------------------ #
    seeds: list[int] = Field(
        default_factory=list,
        description="One seed per requested image for reproducibility",
    )

    # ------------------------------------------------------------------ #
    # Provider configuration (no secrets)                                 #
    # ------------------------------------------------------------------ #
    provider_config: ManifestProviderConfig

    # ------------------------------------------------------------------ #
    # Timestamps                                                           #
    # ------------------------------------------------------------------ #
    created_at: str = Field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat()
    )

    # ------------------------------------------------------------------ #
    # Validators                                                           #
    # ------------------------------------------------------------------ #
    @model_validator(mode="after")
    def validate_age_range(self) -> "GenerationManifest":
        if self.age_min > self.age_max:
            raise ValueError("age_min must be ≤ age_max")
        return self

    @model_validator(mode="after")
    def ensure_seeds(self) -> "GenerationManifest":
        """Auto-generate seeds if the caller did not supply them."""
        if not self.seeds:
            self.seeds = [
                secrets.randbelow(2**32)
                for _ in range(self.requested_count)
            ]
        if len(self.seeds) != self.requested_count:
            raise ValueError(
                f"seeds list length ({len(self.seeds)}) "
                f"must equal requested_count ({self.requested_count})"
            )
        return self

    @model_validator(mode="after")
    def validate_prompts(self) -> "GenerationManifest":
        """When prompts are present, verify length matches requested_count."""
        if self.prompts is not None:
            if len(self.prompts) != self.requested_count:
                raise ValueError(
                    f"prompts list length ({len(self.prompts)}) "
                    f"must equal requested_count ({self.requested_count})"
                )
            if any(not p.strip() for p in self.prompts):
                raise ValueError("All prompts must be non-empty strings")
        return self

    # ------------------------------------------------------------------ #
    # Serialisation helpers                                                #
    # ------------------------------------------------------------------ #
    def to_json(self, *, indent: int = 2) -> str:
        """Serialise the manifest to a pretty-printed JSON string."""
        return self.model_dump_json(indent=indent)

    def save(self, path: Path) -> None:
        """Write the manifest as JSON to *path*, creating parents if needed."""
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(self.to_json(), encoding="utf-8")

    @classmethod
    def load(cls, path: Path) -> "GenerationManifest":
        """Load and validate a manifest from a JSON file."""
        raw = json.loads(path.read_text(encoding="utf-8"))
        return cls.model_validate(raw)


def build_prompt_from_attributes(
    *,
    population_group: str,
    region: str,
    age_min: int,
    age_max: int,
    sex_or_attribute: str,
    skin_tone: str,
    pose: str,
    expression: str,
    lighting: str = "neutral",
    medical_condition: str | None = None,
    medical_severity: str | None = None,
) -> str:
    """
    Build a deterministic, dataset-derived text prompt for image generation.

    This is the single canonical prompt-building function.  Both the mock
    provider and the Kaggle manifest path call this function so the prompt
    wording is consistent.  No secrets or credentials are ever included.

    Example output (fictional, for illustration only)::

        Photorealistic synthetic portrait of a fictional person,
        South Asian, India region, age 25 to 35, female,
        skin tone medium_brown, frontal pose, neutral expression,
        neutral studio lighting. No accessories, sharp facial details,
        plain neutral background, single person, centered face.
    """
    # 6 base descriptive parts (always present).
    descriptive = [
        "Photorealistic synthetic portrait of a fictional person",
        f"{population_group}, {region} region",
        f"age {age_min} to {age_max}, {sex_or_attribute}",
        f"skin tone {skin_tone}",
        f"{pose} pose, {expression} expression",
        f"{lighting} studio lighting",
    ]

    if medical_condition:
        severity_str = f" ({medical_severity})" if medical_severity else ""
        descriptive.append(f"showing {medical_condition}{severity_str}")

    style_constraints = (
        "No glasses, no accessories, no heavy makeup, "
        "sharp facial details, plain neutral background, "
        "single person, centered face, realistic photography."
    )

    return ", ".join(descriptive) + ". " + style_constraints


def build_manifest(
    *,
    dataset_id: int,
    job_id: int,
    dataset,           # Dataset ORM object
    requested_count: int,
    image_width: int,
    image_height: int,
    provider_name: str,
    output_format: str = "png",
    batch_id: str | None = None,
    seeds: list[int] | None = None,
    prompts: list[str] | None = None,
) -> GenerationManifest:
    """
    Convenience factory that builds a GenerationManifest from a Dataset ORM
    object and job identifiers.

    The ``dataset`` parameter is the SQLAlchemy Dataset model instance.
    All fields come from the stored dataset configuration – no user input
    is accepted at submission time to prevent parameter injection.

    Prompts are always generated from dataset attributes using
    ``build_prompt_from_attributes``.  The same prompt is used for every
    image in the batch (one per ``requested_count``) unless the caller
    explicitly overrides via the ``prompts`` parameter.

    Secrets are NEVER included in prompts or manifest fields.
    """
    # Build the dataset-derived prompt once; replicate per requested image.
    custom_prompt = getattr(dataset, "custom_prompt", None)
    if prompts is None:
        if custom_prompt and custom_prompt.strip():
            base_prompt = custom_prompt.strip()
        else:
            base_prompt = build_prompt_from_attributes(
                population_group=dataset.population_group,
                region=dataset.region,
                age_min=dataset.age_min,
                age_max=dataset.age_max,
                sex_or_attribute=dataset.sex_or_attribute,
                skin_tone=dataset.skin_tone,
                pose=dataset.pose,
                expression=dataset.expression,
                medical_condition=dataset.medical_condition,
                medical_severity=dataset.medical_severity,
            )
        prompts = [base_prompt] * requested_count

    patient_id = getattr(dataset, "patient_id", None) or f"P{dataset_id:02d}"

    viewpoint_prompts_raw = getattr(dataset, "viewpoint_prompts", None)
    vp_dict = None
    if isinstance(viewpoint_prompts_raw, dict):
        vp_dict = viewpoint_prompts_raw
    elif isinstance(viewpoint_prompts_raw, str) and viewpoint_prompts_raw.strip():
        try:
            vp_dict = json.loads(viewpoint_prompts_raw)
        except Exception:
            pass

    kwargs: dict[str, Any] = dict(
        dataset_id=dataset_id,
        job_id=job_id,
        patient_id=patient_id,
        custom_prompt=custom_prompt,
        viewpoints=list(VIEWPOINT_KEYS),
        viewpoint_prompts=vp_dict,
        requested_count=requested_count,
        image_width=image_width,
        image_height=image_height,
        population_group=dataset.population_group,
        region=dataset.region,
        age_min=dataset.age_min,
        age_max=dataset.age_max,
        sex_or_attribute=dataset.sex_or_attribute,
        skin_tone=dataset.skin_tone,
        pose=dataset.pose,
        expression=dataset.expression,
        medical_condition=dataset.medical_condition,
        medical_severity=dataset.medical_severity,
        prompts=prompts,
        provider_config=ManifestProviderConfig(
            provider=provider_name,
            output_format=output_format,
        ),
    )
    if batch_id is not None:
        kwargs["batch_id"] = batch_id
    if seeds is not None:
        kwargs["seeds"] = seeds

    return GenerationManifest(**kwargs)
