"""
Direct notebook patcher - applies the prompt validation fix to the notebook
JSON without executing any notebook cells.
"""
import json
from pathlib import Path
import shutil

NB_PATH = Path(r"C:\Users\poter\Downloads\synthetic\kaggle_notebook_check\apac-base-image-only.fixed.ipynb")
BAK_PATH = NB_PATH.with_suffix(".ipynb.bak")

if not NB_PATH.exists():
    print(f"ERROR: Notebook not found: {NB_PATH}")
    exit(1)

# Backup
if not BAK_PATH.exists():
    shutil.copy2(NB_PATH, BAK_PATH)
    print(f"Backed up → {BAK_PATH}")

nb = json.loads(NB_PATH.read_text(encoding="utf-8"))
print(f"Loaded notebook: {len(nb['cells'])} cells")

# Find the manifest reading cell
manifest_cell_idx = None
for i, cell in enumerate(nb["cells"]):
    src = "".join(cell.get("source", []))
    if "requested_count" in src and "GENERATION_SETTINGS" in src and "prompts_value" in src:
        manifest_cell_idx = i
        break

if manifest_cell_idx is None:
    print("ERROR: manifest cell not found")
    exit(1)

print(f"Manifest cell at index {manifest_cell_idx}")
old_source = list(nb["cells"][manifest_cell_idx]["source"])

# Build the replacement cell source as a list of strings
# We rewrite the entire cell source with the corrected logic
new_cell_source = [
    "import json\n",
    "from pathlib import Path\n",
    "\n",
    "# Load the required manifest from Kaggle input.\n",
    "BASE = Path(\"/kaggle/working/rhinoplasty_dataset\")\n",
    "MANIFEST_SEARCH_ROOT = Path(\"/kaggle/input\")\n",
    "\n",
    "manifest_candidates = (\n",
    "    sorted(MANIFEST_SEARCH_ROOT.glob(\"**/manifest.json\"))\n",
    "    if MANIFEST_SEARCH_ROOT.exists()\n",
    "    else []\n",
    ")\n",
    "\n",
    "if not manifest_candidates:\n",
    "    raise RuntimeError(\"Required manifest.json was not found in /kaggle/input.\")\n",
    "\n",
    "MANIFEST_PATH = manifest_candidates[0]\n",
    "with MANIFEST_PATH.open(\"r\", encoding=\"utf-8\") as f:\n",
    "    GENERATION_MANIFEST = json.load(f)\n",
    "\n",
    "GENERATION_SETTINGS = {\n",
    "    \"batch_id\": str(GENERATION_MANIFEST.get(\"batch_id\", \"batch-001\")),\n",
    "    \"requested_count\": int(GENERATION_MANIFEST.get(\"requested_count\", 0)),\n",
    "    \"prompts\": GENERATION_MANIFEST.get(\"prompts\"),\n",
    "    \"seeds\": GENERATION_MANIFEST.get(\"seeds\", []),\n",
    "    \"width\": int(GENERATION_MANIFEST.get(\"width\", GENERATION_MANIFEST.get(\"image_width\", 384))),\n",
    "    \"height\": int(GENERATION_MANIFEST.get(\"height\", GENERATION_MANIFEST.get(\"image_height\", 384))),\n",
    "    \"num_inference_steps\": int(\n",
    "        GENERATION_MANIFEST.get(\"provider_config\", {}).get(\n",
    "            \"num_inference_steps\", GENERATION_MANIFEST.get(\"num_inference_steps\", 12)\n",
    "        )\n",
    "    ),\n",
    "    \"guidance_scale\": float(\n",
    "        GENERATION_MANIFEST.get(\"provider_config\", {}).get(\n",
    "            \"guidance_scale\", GENERATION_MANIFEST.get(\"guidance_scale\", 1.0)\n",
    "        )\n",
    "    ),\n",
    "}\n",
    "\n",
    "if GENERATION_SETTINGS[\"requested_count\"] != 1:\n",
    "    raise ValueError(\"This notebook is configured to generate exactly one base image.\")\n",
    "\n",
    "if len(GENERATION_SETTINGS[\"seeds\"]) != GENERATION_SETTINGS[\"requested_count\"]:\n",
    "    raise ValueError(\n",
    "        \"Manifest must contain exactly one seed per requested image. \"\n",
    "        f\"Requested {GENERATION_SETTINGS['requested_count']}, \"\n",
    "        f\"received {len(GENERATION_SETTINGS['seeds'])} seeds.\"\n",
    "    )\n",
    "\n",
    "# Validate the prompts field.\n",
    "# build_manifest() in the backend always populates this field.\n",
    "# A missing prompts list means the manifest was NOT produced by the backend.\n",
    "# Raise a clear error instead of silently using the hardcoded P01_PROMPT.\n",
    "prompts_value = GENERATION_SETTINGS[\"prompts\"]\n",
    "if prompts_value is None:\n",
    "    raise ValueError(\n",
    "        \"Manifest is missing the required 'prompts' field. \"\n",
    "        \"Ensure the manifest was generated by build_manifest() which always \"\n",
    "        \"populates this field from the dataset configuration.\"\n",
    "    )\n",
    "if not (\n",
    "    isinstance(prompts_value, list)\n",
    "    and len(prompts_value) == GENERATION_SETTINGS[\"requested_count\"]\n",
    "    and all(isinstance(p, str) and p.strip() for p in prompts_value)\n",
    "):\n",
    "    raise ValueError(\"Manifest prompts must be a list of non-empty strings, one per image.\")\n",
    "\n",
    "batch_id = \"\".join(\n",
    "    ch if ch.isalnum() or ch in \"-_\" else \"-\"\n",
    "    for ch in GENERATION_SETTINGS[\"batch_id\"]\n",
    ").strip(\"-\") or \"batch-001\"\n",
    "\n",
    "BATCH_DIR = BASE / \"batches\" / batch_id\n",
    "BATCH_IMAGE_DIR = BATCH_DIR / \"images\"\n",
    "BATCH_IMAGE_DIR.mkdir(parents=True, exist_ok=True)\n",
    "\n",
    "print(\"Batch:\", batch_id)\n",
    "print(\"Requested images:\", GENERATION_SETTINGS[\"requested_count\"])\n",
    "print(\"Dimensions:\", f'{GENERATION_SETTINGS[\"width\"]}x{GENERATION_SETTINGS[\"height\"]}')\n",
    "print(\"Output directory:\", BATCH_DIR)\n",
]

nb["cells"][manifest_cell_idx]["source"] = new_cell_source
nb["cells"][manifest_cell_idx]["outputs"] = []
nb["cells"][manifest_cell_idx]["execution_count"] = None

NB_PATH.write_text(json.dumps(nb, indent=2, ensure_ascii=True), encoding="utf-8")
print(f"Patched notebook saved → {NB_PATH}")
print("Patch complete.")
